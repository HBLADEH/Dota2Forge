def load_hero_catalog() -> HeroCatalog:
    data = json.loads(
        files("dota2forge_core").joinpath("infrastructure/data/heroes.json").read_text("utf-8")
    )
    heroes = tuple(
        Hero(
            row["id"],
            row["display_name"],
            row["english_name"],
            (row["internal_name"].removeprefix("npc_dota_hero_"), *ALIASES.get(row["id"], ())),
        )
        for row in data["heroes"]
    )
    return HeroCatalog(heroes)
